-- Targets intentionally have no cross-domain FK/cascade: a link grants no ownership
-- and must never block independent target deletion or retain a readable orphan.
CREATE TABLE plugin_component_link (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES plugin_project(id),
 kind VARCHAR(16) NOT NULL CHECK(kind IN ('SKILL','MCP')),
 target_id BIGINT NOT NULL,
 created_by VARCHAR(128) NOT NULL REFERENCES user_account(id),
 created_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT uk_plugin_component_target UNIQUE(project_id,kind,target_id)
);
